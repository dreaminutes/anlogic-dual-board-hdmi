`timescale 1ns/1ps
// Independent feasibility probe, never instantiated by the frozen renderer.
// Input local coordinates are Cartesian Q4 after one shared axis projection.
module db_neon_cartesian_panel_shader(input clk,input valid,input signed[9:0]u_q4,input signed[11:0]v_q4,
